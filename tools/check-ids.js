function check(id) {
  return new Promise((resolve) => {
    const url = 'https://images.unsplash.com/photo-' + id + '?auto=format&fit=crop&w=100&q=60';
    const req = https.get(url, (res) => {
      res.resume();
      resolve({ id, status: res.statusCode, type: res.headers['content-type'] });
    });
    req.on('error', (e) => resolve({ id, status: 'ERR', type: e.message }));
    req.setTimeout(15000, () => { req.destroy(); resolve({ id, status: 'TIMEOUT', type: '' }); });
  });
}

